async (page) => {
  await page.unrouteAll({behavior:'wait'});
  await page.goto('http://localhost:5181/login');
  await page.evaluate(()=>localStorage.clear());
  await page.reload();
  await page.evaluate(()=>{window.confirm=()=>true;});
  const fixtures = await (await page.request.get('http://127.0.0.1:18001/__smoke/session')).json();
  const failures = [];
  page.on('pageerror', e => failures.push(e.message));
  await page.route('https://proyecto-test.supabase.co/auth/v1/**', async route => {
    const path = new URL(route.request().url()).pathname;
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(path.endsWith('/user')?fixtures.session.user:path.endsWith('/logout')?{}:fixtures.session)});
  });
  let pdfDownloads = 0;
  await page.route('https://proyecto-test.supabase.co/storage/**', async route => {
    if (route.request().headers()['authorization']) throw new Error('Se envió JWT a Storage');
    pdfDownloads++;
    const pdf = await page.request.get('http://127.0.0.1:18001/__smoke/pdf');
    await route.fulfill({status:200,contentType:'application/pdf',body:await pdf.body(),headers:{'access-control-allow-origin':'http://localhost:5181'}});
  });
  await page.getByRole('textbox',{name:'Correo',exact:true}).fill('usuario@ejemplo.co');
  await page.getByRole('textbox',{name:'Contraseña',exact:true}).fill('SyntheticPass123!');
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
  await page.waitForURL('**/licitaciones');
  await page.getByText('Pliego de integración',{exact:true}).waitFor();
  await page.getByRole('link',{name:'Abrir →',exact:true}).first().click();
  await page.getByRole('heading',{name:'Pliego de integración',exact:true}).waitFor();
  await page.getByRole('tab',{name:'Pliego y evidencia',exact:true}).click();
  await page.getByLabel('Seleccionar ítem').selectOption({index:1});
  await page.locator('canvas').waitFor();
  await page.locator('.pdf-highlight').waitFor();
  const initialDownloads=pdfDownloads;
  await page.getByLabel('Seleccionar ítem').selectOption('');
  await page.getByLabel('Seleccionar ítem').selectOption({index:1});
  if (pdfDownloads !== initialDownloads) throw new Error('Cambiar selección no debe descargar el PDF otra vez');
  await page.getByRole('tab',{name:/Revisión \(/}).click();
  await page.locator('summary').filter({hasText:'Acreditar experiencia'}).click();
  await page.getByLabel('Justificación obligatoria').fill('Soporte comprobado durante integración sintética.');
  await page.getByRole('button',{name:'Guardar revisión y reevaluar'}).click();
  await page.getByRole('tab',{name:'Resumen',exact:true}).click();
  await page.getByText('Resultado sintético de integración: requisito revisado.',{exact:true}).waitFor();
  await page.getByRole('tab',{name:'Chat y observaciones',exact:true}).click();
  await page.getByLabel('Pregunta',{exact:true}).fill('¿Qué experiencia se exige?');
  await page.getByRole('button',{name:'Enviar pregunta',exact:true}).click();
  await page.getByText('El numeral 3.1 exige experiencia acreditada.',{exact:true}).waitFor();
  await page.getByRole('combobox',{name:'Requisito ambiguo',exact:true}).selectOption({index:1});
  await page.getByRole('button',{name:'Generar borrador',exact:true}).click();
  await page.getByRole('heading',{name:'Solicitud de aclaración',exact:true}).waitFor();
  const [xlsx] = await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Descargar Excel',exact:true}).click()]);
  if (!xlsx.suggestedFilename().endsWith('.xlsx')) throw new Error('No se recibió XLSX');
  await page.screenshot({path:'test-results/connected-analysis.png',fullPage:true});
  await page.getByRole('link',{name:'Miembros',exact:true}).click();
  await page.getByLabel('Correo',{exact:true}).fill('nuevo@ejemplo.co');
  await page.getByRole('button',{name:'Enviar invitación',exact:true}).click();
  await page.getByRole('cell',{name:'nuevo@ejemplo.co',exact:true}).waitFor();
  await page.getByRole('row').filter({hasText:'nuevo@ejemplo.co'}).getByRole('button',{name:'Cambiar rol',exact:true}).click();
  await page.getByRole('row').filter({hasText:'nuevo@ejemplo.co'}).getByRole('cell',{name:'administrador',exact:true}).waitFor();
  await page.getByRole('row').filter({hasText:'nuevo@ejemplo.co'}).getByRole('button',{name:'Retirar',exact:true}).click();
  await page.getByRole('cell',{name:'nuevo@ejemplo.co',exact:true}).waitFor({state:'detached'});
  await page.getByRole('link',{name:'Conocimiento',exact:true}).click();
  const sample = await (await page.request.get('http://localhost:5181/base-conocimiento-ejemplo.json')).body();
  await page.getByLabel('Archivo JSON',{exact:true}).setInputFiles({name:'empresa.json',mimeType:'application/json',buffer:sample});
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Cargar e indexar',exact:true}).click();
  await page.getByRole('heading',{name:'Soluciones Andinas de Ingeniería S.A.S.',exact:true}).waitFor();
  await page.getByRole('button',{name:'Volver a indexar',exact:true}).waitFor();
  // Verifica el dato persistido por el endpoint real de conocimiento.
  const summary = await page.request.get('http://127.0.0.1:18001/api/conocimiento',{headers:{Authorization:'Bearer '+fixtures.session.access_token}});
  if (!summary.ok() || !(await summary.json()).cargada) throw new Error('La base de conocimiento no se guardó');
  await page.getByRole('link',{name:'Cargar pliego',exact:true}).click();
  const pdf = await (await page.request.get('http://127.0.0.1:18001/__smoke/pdf')).body();
  await page.getByLabel('Arrastra el pliego o selecciona un archivo').setInputFiles({name:'pliego-nuevo.pdf',mimeType:'application/pdf',buffer:pdf});
  await page.getByRole('button',{name:'Iniciar análisis',exact:true}).click();
  await page.waitForURL(/\/licitaciones\/[a-f0-9-]+(\/progreso)?$/);
  await page.getByRole('heading',{name:'pliego-nuevo.pdf',exact:true}).waitFor();
  await page.getByRole('link',{name:'Licitaciones',exact:true}).first().click();
  await page.getByText('pliego-nuevo.pdf',{exact:true}).first().waitFor();
  await page.getByRole('button',{name:'Cerrar sesión',exact:true}).click();
  await page.getByRole('heading',{name:'Bienvenido a CRITERIO',exact:true}).waitFor();
  if(failures.length) throw new Error(failures.join('; '));
  console.log('SMOKE OK: sesión, JWT/API, listado, matriz, PDF/resaltado sin JWT externo, revisión persistida/reevaluación, chat/citas, observaciones, XLSX, miembros, conocimiento JSON y subida/progreso; proveedores simulados.');
}